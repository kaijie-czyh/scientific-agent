"""创新点套路知识库（innovation playbook）。

来源：科研方法论沉淀的「5 大创新套路」+「问题×方法组合定位矩阵」。
用于锚定两处 LLM 创新建议，防止天马行空：
  1. topic_discovery.TopicRecommendAgent —— 方向推荐的 innovation_point 字段
  2. ideation.BrainstormAgent —— 候选研究思路生成

设计原则：每条创新建议必须能归入五大套路之一、必须声明所用套路、
必须从给定文献/趋势证据出发推导，不得凭空捏造"全新理论"。
"""

from __future__ import annotations

# 五大创新套路（难度系数 / 新手适配度 / 套路说明）
INNOVATION_PATTERNS_PROMPT = """
【创新点套路锚定（必须遵守）】
你提出的每一条创新建议，都必须归入以下五大套路之一，并在 innovation_pattern 字段
填入对应标签（application / modification / fusion / comparison / theory）。
禁止提出无法归类的"天马行空"式创新；禁止在没有证据支撑时宣称"从无到有的全新理论"。

1. application 应用创新（难度★★★，新手首选）
   把领域内已有成熟方法迁移到一个新的应用场景/研究对象/数据模态上。
   关键是"迁移"要有明确动机：新场景与原场景存在结构相似性，且原方法在新场景
   尚无人验证或存在明显适配问题。落到具体：什么方法 → 迁到什么对象/场景 → 预期解决什么问题。

2. modification 修改创新（难度★★★，新手首选）
   对现有方法做局部改进：替换弱模块、增加约束/正则、简化过重设计、调整流程顺序。
   改动点必须针对某篇具体论文的明确不足（其自述 limitation / FutureWork / 实验空白），
   并说明为什么这个改动有望带来可度量的提升。

3. fusion 融合创新（难度★★★，适合有一定积累者）
   把两条已有技术路线组合成新方法（"缝合怪"）：A 的理论/模块 + B 的机制/场景，
   组合的合理性来自它们恰好互补地覆盖同一问题的不同侧面。
   必须说明：各取什么、为什么互补、组合后解决单条路线都解决不了什么。

4. comparison 比较创新（难度★★★，适合评测/分析型选题）
   做合格的"测评师"：对已有方法/理论 A/B/C/D 做系统化对比实验，
   统一数据集与指标，取其精华去其糟粕，产出可复用的结论与选型/应用建议。
   落点可以是 benchmark、消融研究、或"何时该用哪种方法"的决策依据。

5. theory 理论及方法创新（难度★★★★★，不建议新手选择）
   提出新问题 + 新理论框架/新评判方法，从无到有。
   只有当给定文献证据中出现明确的现有理论失效/解释不了的现象时才允许提出；
   且必须明确说明新框架与最接近的现有框架的本质区别。

【问题×方法组合定位（用于安排核查，不用于预测发表档次）】
- 新问题 + 新方法：分别核实问题价值、方法差异与可检验性，不能据此承诺顶刊。
- 老问题 + 新方法：与最接近的方法逐项比较，检查改动是否解决真实局限。
- 新问题 + 老方法：核实新场景是否带来新的困难或有价值的观察，不能只替换数据集。
- 老问题 + 老方法：仍可能有复现、反证、边界条件或公平评测价值，不自动排除。
这张矩阵不能决定 novelty 高低、录用概率或发表层次。
五类套路只是候选思考工具，不要求每类各生成一个方向，不以套路标签代替创新性证据。
文献未报告某信息可能源于摘要不完整或解析缺失，不能直接认定领域无人研究。
提出创新建议时说明最接近的已有工作、具体差异、核查范围与尚未核实的部分。
""".strip()

