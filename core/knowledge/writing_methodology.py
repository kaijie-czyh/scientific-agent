def build_stage_writing_hint(stage: str, domain: str = "") -> str:
    """按阶段生成写作方法论要点提示（轻注入，供各阶段 system prompt 拼接）。

    Args:
        stage: 阶段标识（topic_discovery / research / ideation / experiment / writing）
        domain: 研究领域（用于领域适配措辞）

    Returns:
        一段可拼进 system prompt 的要点文本；未知阶段返回空串。
    """
    hint = _STAGE_WRITING_HINTS.get(str(stage or "").strip().lower(), "")
    if not hint:
        return ""
    label = domain_label(domain)
    if label and label != "通用（自定义领域）":
        hint += f"\n（当前研究领域：{label}，涉及领域口径的表述按该领域惯例处理。）"
    return hint
